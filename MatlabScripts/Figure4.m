%% =========================
%  Local function
% ==========================
function draw2DErrorBarsAsym(x, y, ...
                             xerr_minus, xerr_plus, ...
                             yerr_minus, yerr_plus, ...
                             lineColor, lineWidth)

    capFrac = 0.015;

    xRange = max(x, [], 'omitnan') - min(x, [], 'omitnan');
    yRange = max(y, [], 'omitnan') - min(y, [], 'omitnan');

    if xRange <= 0 || isnan(xRange)
        xRange = 1;
    end

    if yRange <= 0 || isnan(yRange)
        yRange = 1;
    end

    xCap = capFrac * xRange;
    yCap = capFrac * yRange;

    for i = 1:numel(x)

        x1 = x(i) - xerr_minus(i);
        x2 = x(i) + xerr_plus(i);

        y1 = y(i) - yerr_minus(i);
        y2 = y(i) + yerr_plus(i);

        %% Horizontal error bar
        if all(isfinite([x1, x2, y(i)]))
            line([x1, x2], [y(i), y(i)], ...
                'Color', lineColor, ...
                'LineWidth', lineWidth);

            line([x1, x1], [y(i)-yCap, y(i)+yCap], ...
                'Color', lineColor, ...
                'LineWidth', lineWidth);

            line([x2, x2], [y(i)-yCap, y(i)+yCap], ...
                'Color', lineColor, ...
                'LineWidth', lineWidth);
        end

        %% Vertical error bar
        if all(isfinite([x(i), y1, y2]))
            line([x(i), x(i)], [y1, y2], ...
                'Color', lineColor, ...
                'LineWidth', lineWidth);

            line([x(i)-xCap, x(i)+xCap], [y1, y1], ...
                'Color', lineColor, ...
                'LineWidth', lineWidth);

            line([x(i)-xCap, x(i)+xCap], [y2, y2], ...
                'Color', lineColor, ...
                'LineWidth', lineWidth);
        end
    end
end