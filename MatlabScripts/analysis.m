clear; clc;

%% Files
referenceFile = 'DE_connection_reference.mat';
finalFile     = 'PartFloating_0600.csv';
resultFile    = 'DE_remaining_bonds_0600.mat';

%% Load reference
S = load(referenceFile, 'Reference');
Reference = S.Reference;
BondParticles = Reference.BondParticles;
Interfaces    = Reference.Interfaces;

refIdp      = BondParticles.Idp;
refCorner   = BondParticles.IsCorner;
refIfaceID  = double(BondParticles.InterfaceID);
nonCorner   = ~refCorner;
numIfaces   = height(Interfaces);

%% Read final file
required = {'Pos.x [m]', 'Pos.y [m]', 'Pos.z [m]', 'Idp', 'DemBond'};

opts = detectImportOptions(finalFile, ...
    'Delimiter', ';', ...
    'NumHeaderLines', 3, ...
    'VariableNamingRule', 'preserve');

missing = setdiff(required, opts.VariableNames);
if ~isempty(missing)
    error('Missing CSV columns: %s', strjoin(missing, ', '));
end

opts.SelectedVariableNames = required;
T = readtable(finalFile, opts);

xF       = double(T.('Pos.x [m]'));
yF       = double(T.('Pos.y [m]'));
zF       = double(T.('Pos.z [m]'));
idpF     = uint32(T.Idp);
demBondF = double(T.DemBond);

clear T

%% Match final particles to reference particles by Idp
[tf, loc] = ismember(refIdp, idpF);
if ~all(tf)
    error('Some reference Idp values were not found in the final file.');
end

xNow       = xF(loc);
yNow       = yF(loc);
zNow       = zF(loc);
demBondNow = demBondF(loc);

clear xF yF zF idpF demBondF loc tf

%% Remaining particle bonds (ignore corner particles)
activeParticle = (demBondNow == 1) & nonCorner;
brokenParticle = (demBondNow == 0) & nonCorner;
unexpectedTwo  = (demBondNow == 2) & nonCorner;

if any(unexpectedTwo)
    error('Some non-corner reference bond particles became DemBond = 2.');
end

%% Remaining DE-to-DE interfaces
activeCounts = accumarray(refIfaceID(nonCorner), double(activeParticle(nonCorner)), [numIfaces 1], @sum, 0);
brokenCounts = accumarray(refIfaceID(nonCorner), double(brokenParticle(nonCorner)), [numIfaces 1], @sum, 0);
totalCounts  = accumarray(refIfaceID(nonCorner), 1, [numIfaces 1], @sum, 0);

isConnected = activeCounts > 0;
isBroken    = activeCounts == 0;

Interfaces.NumReferenceParticles = uint32(totalCounts);
Interfaces.NumActiveParticles    = uint32(activeCounts);
Interfaces.NumBrokenParticles    = uint32(brokenCounts);
Interfaces.IsConnected           = isConnected;
Interfaces.IsBroken              = isBroken;

%% Per-particle output table
ParticleStatus = table( ...
    refIdp, ...
    BondParticles.DE_ID, ...
    BondParticles.DE_X, BondParticles.DE_Y, BondParticles.DE_Z, ...
    BondParticles.IsCorner, ...
    BondParticles.Orientation, ...
    BondParticles.InterfaceID, ...
    BondParticles.DE1, BondParticles.DE2, ...
    single(BondParticles.X0), single(BondParticles.Y0), single(BondParticles.Z0), ...
    single(xNow), single(yNow), single(zNow), ...
    uint8(demBondNow), ...
    logical(activeParticle), ...
    'VariableNames', { ...
        'Idp', ...
        'DE_ID', ...
        'DE_X', 'DE_Y', 'DE_Z', ...
        'IsCorner', ...
        'Orientation', ...
        'InterfaceID', ...
        'DE1', 'DE2', ...
        'X0', 'Y0', 'Z0', ...
        'X', 'Y', 'Z', ...
        'DemBondFinal', ...
        'IsActiveNonCorner'});

%% Save results
Analysis.ReferenceFile = referenceFile;
Analysis.FinalFile = finalFile;
Analysis.ParticleStatus = ParticleStatus;
Analysis.Interfaces = Interfaces;
Analysis.NumConnectedInterfaces = nnz(isConnected);
Analysis.NumBrokenInterfaces    = nnz(isBroken);
Analysis.NumActiveNonCornerParticles = nnz(activeParticle);
Analysis.NumBrokenNonCornerParticles = nnz(brokenParticle);

save(resultFile, 'Analysis', '-v7.3');

fprintf('Corner particles ignored: %d\n', nnz(refCorner));
fprintf('Connected interfaces remaining: %d / %d\n', nnz(isConnected), numIfaces);
fprintf('Broken interfaces: %d / %d\n', nnz(isBroken), numIfaces);

%% Top view plot of remaining bonds at initial locations
fig = figure('Color', 'w');

xPlot = double(BondParticles.X0(activeParticle));
yPlot = double(BondParticles.Y0(activeParticle));

scatter(xPlot, yPlot, 3, 'r', 'filled', ...
    'MarkerFaceAlpha', 0.85, ...
    'MarkerEdgeAlpha', 0);
hold on

x0 = Reference.Origin(1);
y0 = Reference.Origin(2);

sheetLx = Reference.NumDE(1) * Reference.ElementSize(1);
sheetLy = Reference.NumDE(2) * Reference.ElementSize(2);

rectangle('Position', [x0, y0, sheetLx, sheetLy], ...
    'EdgeColor', 'k', ...
    'LineWidth', 2.5);

axis equal
xlim([x0, x0 + sheetLx]);
ylim([y0, y0 + sheetLy]);

xlabel('x [m]');
ylabel('y [m]');
title(sprintf('Initial-location remaining bonds: %d connected / %d total interfaces', ...
    nnz(isConnected), numIfaces), ...
    'FontWeight', 'bold');

set(gca, ...
    'FontSize', 14, ...
    'LineWidth', 1.2, ...
    'Box', 'on');

drawnow
fig = figure('Color', 'w');
%% Compare top, middle, and bottom 1 mm remaining bonds

zRef = double(BondParticles.Z0);

bandThickness = 5e-3;      % 1 dp
halfBand      = bandThickness / 2;
zTol          = 1e-10;

zMin = min(zRef(nonCorner));
zMax = max(zRef(nonCorner));
zMid = 0.5 * (zMin + zMax);

% Top 1 mm measured downward from the highest bond-particle layer
topBand = nonCorner & ...
    (zRef >= zMax - bandThickness - zTol);

% Middle 1 mm centered on the sheet midplane
middleBand = nonCorner & ...
    (zRef >= zMid - halfBand - zTol) & ...
    (zRef <= zMid + halfBand + zTol);

% Bottom 1 mm measured upward from the lowest bond-particle layer
bottomBand = nonCorner & ...
    (zRef <= zMin + bandThickness + zTol);

topActive    = activeParticle & topBand;
middleActive = activeParticle & middleBand;
bottomActive = activeParticle & bottomBand;

fprintf('\nTHROUGH-THICKNESS BANDS\n');
fprintf('Reference z range: %.6f to %.6f m\n', zMin, zMax);
fprintf('Reference midplane: %.6f m\n', zMid);
fprintf('Band thickness: %.4f m\n', bandThickness);

fprintf('Top band:    %.6f to %.6f m\n', ...
    zMax - bandThickness, zMax);

fprintf('Middle band: %.6f to %.6f m\n', ...
    zMid - halfBand, zMid + halfBand);

fprintf('Bottom band: %.6f to %.6f m\n', ...
    zMin, zMin + bandThickness);

fprintf('Top active particles:    %d\n', nnz(topActive));
fprintf('Middle active particles: %d\n', nnz(middleActive));
fprintf('Bottom active particles: %d\n', nnz(bottomActive));

if ~any(topBand)
    warning('No reference particles were found in the top 1 mm band.');
end

if ~any(middleBand)
    warning(['No reference particles were found in the middle 1 mm band. ', ...
             'Your particle layers may not intersect the exact midplane band.']);
end

if ~any(bottomBand)
    warning('No reference particles were found in the bottom 1 mm band.');
end

%% Sheet geometry

x0 = double(Reference.Origin(1));
y0 = double(Reference.Origin(2));

sheetLx = double(Reference.NumDE(1)) * ...
          double(Reference.ElementSize(1));

sheetLy = double(Reference.NumDE(2)) * ...
          double(Reference.ElementSize(2));

%% Top, middle, bottom, and overlay plots

figure('Color', 'w');

tl = tiledlayout(4, 1, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

%% Top 1 mm

nexttile

scatter( ...
    double(BondParticles.X0(topActive)), ...
    double(BondParticles.Y0(topActive)), ...
    4, ...
    'r', ...
    'filled', ...
    'MarkerFaceAlpha', 0.85, ...
    'MarkerEdgeAlpha', 0);

hold on

rectangle( ...
    'Position', [x0, y0, sheetLx, sheetLy], ...
    'EdgeColor', 'k', ...
    'LineWidth', 2);

axis equal
xlim([x0, x0 + sheetLx]);
ylim([y0, y0 + sheetLy]);

ylabel('y [m]');

title(sprintf( ...
    'Top 5 mm: %d active bond particles', ...
    nnz(topActive)), ...
    'FontWeight', 'bold');

set(gca, ...
    'FontSize', 13, ...
    'LineWidth', 1.1, ...
    'Box', 'on');

%% Middle 1 mm

nexttile

scatter( ...
    double(BondParticles.X0(middleActive)), ...
    double(BondParticles.Y0(middleActive)), ...
    4, ...
    'k', ...
    'filled', ...
    'MarkerFaceAlpha', 0.85, ...
    'MarkerEdgeAlpha', 0);

hold on

rectangle( ...
    'Position', [x0, y0, sheetLx, sheetLy], ...
    'EdgeColor', 'k', ...
    'LineWidth', 2);

axis equal
xlim([x0, x0 + sheetLx]);
ylim([y0, y0 + sheetLy]);

ylabel('y [m]');

title(sprintf( ...
    'Middle 5 mm: %d active bond particles', ...
    nnz(middleActive)), ...
    'FontWeight', 'bold');

set(gca, ...
    'FontSize', 13, ...
    'LineWidth', 1.1, ...
    'Box', 'on');

%% Bottom 1 mm

nexttile

scatter( ...
    double(BondParticles.X0(bottomActive)), ...
    double(BondParticles.Y0(bottomActive)), ...
    4, ...
    'b', ...
    'filled', ...
    'MarkerFaceAlpha', 0.85, ...
    'MarkerEdgeAlpha', 0);

hold on

rectangle( ...
    'Position', [x0, y0, sheetLx, sheetLy], ...
    'EdgeColor', 'k', ...
    'LineWidth', 2);

axis equal
xlim([x0, x0 + sheetLx]);
ylim([y0, y0 + sheetLy]);

ylabel('y [m]');

title(sprintf( ...
    'Bottom 5 mm: %d active bond particles', ...
    nnz(bottomActive)), ...
    'FontWeight', 'bold');

set(gca, ...
    'FontSize', 13, ...
    'LineWidth', 1.1, ...
    'Box', 'on');

%% Three-band overlay

nexttile

hTop = scatter( ...
    double(BondParticles.X0(topActive)), ...
    double(BondParticles.Y0(topActive)), ...
    7, ...
    'r', ...
    'filled', ...
    'MarkerFaceAlpha', 0.40, ...
    'MarkerEdgeAlpha', 0);

hold on

hMiddle = scatter( ...
    double(BondParticles.X0(middleActive)), ...
    double(BondParticles.Y0(middleActive)), ...
    5, ...
    'k', ...
    'filled', ...
    'MarkerFaceAlpha', 0.35, ...
    'MarkerEdgeAlpha', 0);

hBottom = scatter( ...
    double(BondParticles.X0(bottomActive)), ...
    double(BondParticles.Y0(bottomActive)), ...
    7, ...
    'b', ...
    'filled', ...
    'MarkerFaceAlpha', 0.40, ...
    'MarkerEdgeAlpha', 0);

rectangle( ...
    'Position', [x0, y0, sheetLx, sheetLy], ...
    'EdgeColor', 'k', ...
    'LineWidth', 2);

axis equal
xlim([x0, x0 + sheetLx]);
ylim([y0, y0 + sheetLy]);

xlabel('x [m]');
ylabel('y [m]');
title('Top, middle, and bottom 1 mm overlay', ...
    'FontWeight', 'bold');

legend( ...
    [hTop, hMiddle, hBottom], ...
    {'Top 5 mm', 'Middle 5 mm', 'Bottom 5 mm'}, ...
    'Location', 'eastoutside');

set(gca, ...
    'FontSize', 13, ...
    'LineWidth', 1.1, ...
    'Box', 'on');

title(tl, ...
    'Remaining bonds at three positions through the thickness', ...
    'FontSize', 16, ...
    'FontWeight', 'bold');

drawnow