%  INPUT WAVEFORM VS LOCAL CURVATURE/STRESS
%
%  CSV format:
%      Row 1:      time [s], x = 0.123 m, x = 0.456 m, ...
%      Row 2:end:  time, eta(x1,t), eta(x2,t), ...
%
%  The input waveform uses:
%      - prescribed input amplitude
%      - prescribed input wavelength
%      - best-fitting phase and vertical offset at each time
%
%  Local curvature is obtained from a moving quadratic fit.
%% ============================================================

clear;
clc;
close all;
%% ============================================================

%% USER SETTINGS

filename = "eta_no_overwash_vs_x_time.csv";

% Prescribed wave input
inputAmplitude  = 0.025;     % wave amplitude a [m]
inputWavelength = 4.4579;    % wavelength lambda [m]

% Plate/material properties
E = 5.0e6;                   % Young's modulus [Pa]
h = 0.05;                    % plate thickness [m]
stressThreshold = 9000;      % stress threshold [Pa]

% x-range used for ALL curvature/stress analysis
analysisXMin = 1.0;          % [m]
analysisXMax = 10.0;         % [m]

% Local curvature calculation
curvatureMethod = "localfit";   % "localfit" or "gradient"
fitHalfWidth = 0.614;           % local-fit half-width [m]

% Plot controls
makePlots = true;
plotCompareTimes = [5, 30, 60];

% Figure 1 settings
stressPlotTime = 60.0;
plateWidth = 0.84;

% Camera orientation obtained from ParaView
stressViewAzimuth   = -29.4089401836;
stressViewElevation =  16.3217025468;
stressCameraRoll    =   1.8583120658;

% Optional local-stress movie
makeStressMovie = true;
stressMovieFPS = 10;
stressMovieName = "finalStress_movie.mp4";


%% CHECK INPUTS

if ~isfinite(inputAmplitude) || inputAmplitude <= 0
    error("Enter a positive value for inputAmplitude.");
end

if ~isfinite(inputWavelength) || inputWavelength <= 0
    error("Enter a positive value for inputWavelength.");
end


%% BASIC DERIVED VALUES

kInput = 2*pi/inputWavelength;

strainThreshold = stressThreshold/E;
kappaThreshold = stressThreshold/(E*h/2);

% Maximum bending stress for prescribed input waveform
inputWaveMaxStress = ...
    E*(h/2)*kInput^2*inputAmplitude;

fprintf("===== SETTINGS =====\n");
fprintf("Input amplitude = %.6g m\n", inputAmplitude);
fprintf("Input wavelength = %.6g m\n", inputWavelength);
fprintf("Input wavenumber = %.6g rad/m\n", kInput);

fprintf( ...
    "Input-wave maximum stress = %.6g Pa\n", ...
    inputWaveMaxStress);

fprintf( ...
    "Stress threshold = %.6g Pa\n", ...
    stressThreshold);

fprintf( ...
    "Strain threshold = %.6g\n", ...
    strainThreshold);

fprintf( ...
    "Curvature threshold = %.6g 1/m\n", ...
    kappaThreshold);


%% READ ELEVATION FILE

[x, time, eta] = ...
    readEtaWithHeaderCSV(filename);


%% RESTRICT ALL ANALYSIS TO x = 1 TO 10 m

idxAnalysisX = ...
    x >= analysisXMin & ...
    x <= analysisXMax;

if sum(idxAnalysisX) < 3

    error( ...
        "Fewer than 3 x-locations exist between %.3f and %.3f m.", ...
        analysisXMin, ...
        analysisXMax);

end

x = x(idxAnalysisX);
eta = eta(:,idxAnalysisX);

fprintf( ...
    "Analysis restricted to x = %.3f to %.3f m (%d x-locations).\n", ...
    analysisXMin, ...
    analysisXMax, ...
    length(x));

part = (1:length(time))';

dx = median(diff(x), "omitnan");

Nx = length(x);
Nt = length(time);


%% LOCAL CURVATURE, STRAIN, AND STRESS

kappa_xt = nan(Nt,Nx);
strain_top_xt = nan(Nt,Nx);
stress_top_xt = nan(Nt,Nx);
eta_localfit_xt = nan(Nt,Nx);

for it = 1:Nt

    y = fillEtaRow( ...
        eta(it,:), ...
        x);

    if all(~isfinite(y))
        continue;
    end

    etaLocalFit = y;


    if curvatureMethod == "gradient"

        dy_dx = gradient(y,dx);
        d2y_dx2 = gradient(dy_dx,dx);

        % Full geometric curvature
        kappa = ...
            d2y_dx2 ./ ...
            (1 + dy_dx.^2).^(3/2);


    elseif curvatureMethod == "localfit"

        kappa = nan(1,Nx);
        etaLocalFit = nan(1,Nx);

        for ix = 1:Nx

            x0 = x(ix);

            idxLocal = ...
                abs(x-x0) <= fitHalfWidth;

            if sum(idxLocal) < 3
                continue;
            end

            xLocal = ...
                x(idxLocal)-x0;

            yLocal = ...
                y(idxLocal);

            % Local quadratic:
            %
            % eta = c0 + c1(x-x0) + c2(x-x0)^2

            p = polyfit( ...
                xLocal, ...
                yLocal, ...
                2);

            c2 = p(1);
            c1 = p(2);
            c0 = p(3);

            etaLocalFit(ix) = c0;

            % Geometric curvature at x0
            kappa(ix) = ...
                (2*c2) / ...
                (1+c1^2)^(3/2);

        end

        etaLocalFit = ...
            fillEtaRow( ...
            etaLocalFit, ...
            x);

        kappa = ...
            fillEtaRow( ...
            kappa, ...
            x);


    else

        error( ...
            "curvatureMethod must be " + ...
            "'gradient' or 'localfit'.");

    end


    % Top-surface bending strain
    strainTop = ...
        -(h/2)*kappa;

    % Top-surface bending stress
    stressTop = ...
        E*strainTop;


    kappa_xt(it,:) = ...
        kappa;

    strain_top_xt(it,:) = ...
        strainTop;

    stress_top_xt(it,:) = ...
        stressTop;

    eta_localfit_xt(it,:) = ...
        etaLocalFit;

end


absStress_xt = ...
    abs(stress_top_xt);

% Maximum local absolute stress between x = 1 and 10 m
sigmaLocalMaxTime = ...
    max( ...
    absStress_xt, ...
    [], ...
    2, ...
    "omitnan");


%% INPUT WAVEFORM

% Amplitude and wavelength remain fixed.
% Phase and vertical offset are fitted using ONLY x = 1 to 10 m.

eta_input_xt = ...
    nan(Nt,Nx);

kappa_input_xt = ...
    nan(Nt,Nx);

stress_input_xt = ...
    nan(Nt,Nx);

inputPhaseTime = ...
    nan(Nt,1);

inputOffsetTime = ...
    nan(Nt,1);


% Basis used to determine best phase
Xphase = [ ...
    cos(kInput*x(:)), ...
    sin(kInput*x(:))];


for it = 1:Nt

    y = fillEtaRow( ...
        eta(it,:), ...
        x);

    if all(~isfinite(y))
        continue;
    end


    % Vertical offset
    offset = ...
        mean( ...
        y, ...
        "omitnan");

    yCentered = ...
        y-offset;


    % Best phase for prescribed wavelength
    beta = ...
        Xphase \ yCentered(:);

    betaNorm = ...
        hypot( ...
        beta(1), ...
        beta(2));


    if betaNorm > eps

        phaseCos = ...
            beta(1)/betaNorm;

        phaseSin = ...
            beta(2)/betaNorm;

    else

        phaseCos = 1;
        phaseSin = 0;

    end


    % Prescribed input waveform
    etaOscillatory = ...
        inputAmplitude*( ...
        phaseCos*cos(kInput*x) + ...
        phaseSin*sin(kInput*x));


    etaInput = ...
        offset + ...
        etaOscillatory;


    % Curvature of prescribed input waveform
    kappaInput = ...
        -kInput^2 * ...
        etaOscillatory;


    % Input-wave bending stress
    stressInput = ...
        -E*(h/2)*kappaInput;


    eta_input_xt(it,:) = ...
        etaInput;

    kappa_input_xt(it,:) = ...
        kappaInput;

    stress_input_xt(it,:) = ...
        stressInput;


    inputPhaseTime(it) = ...
        atan2( ...
        phaseSin, ...
        phaseCos);

    inputOffsetTime(it) = ...
        offset;

end


sigmaInputMaxTime = ...
    repmat( ...
    inputWaveMaxStress, ...
    Nt, ...
    1);


localToInputStressRatio = ...
    sigmaLocalMaxTime / ...
    inputWaveMaxStress;


%% SAVE RESULTS

summaryTable = table();

