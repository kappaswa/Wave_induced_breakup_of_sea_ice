function [x,time,eta] = ...
        readEtaWithHeaderCSV(filename)

    C = ...
        readcell(filename);


    if size(C,1) < 2 || ...
            size(C,2) < 2

        error( ...
            "CSV does not contain a " + ...
            "header row followed by data.");

    end


    headers = ...
        C(1,:);

    raw = ...
        C(2:end,:);


    time = ...
        cellColumnToDouble( ...
        raw(:,1));


    eta = ...
        cellBlockToDouble( ...
        raw(:,2:end));


    x = ...
        nan( ...
        1, ...
        numel(headers)-1);


    for j = 2:numel(headers)

        headerText = ...
            string( ...
            headers{j});


        token = ...
            regexp( ...
            headerText, ...
            "[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", ...
            "match");


        if ~isempty(token)

            x(j-1) = ...
                str2double( ...
                token{1});

        end

    end


    % Remove unusable x columns
    goodX = ...
        isfinite(x);

    x = ...
        x(goodX);

    eta = ...
        eta(:,goodX);


    % Remove unusable time rows
    goodT = ...
        isfinite(time);

    time = ...
        time(goodT);

    eta = ...
        eta(goodT,:);


    % Force x to row vector
    x = ...
        x(:)';


    % Sort by x
    [x,ix] = ...
        sort(x);

    eta = ...
        eta(:,ix);


    fprintf( ...
        "Read file: %s\n", ...
        filename);


    fprintf( ...
        "Read %d time steps and %d x-locations.\n", ...
        length(time), ...
        length(x));

end


function v = cellColumnToDouble(c)

    v = ...
        nan( ...
        size(c,1), ...
        1);


    for i = 1:size(c,1)

        item = ...
            c{i,1};


        if isnumeric(item)

            v(i) = ...
                item;


        elseif ...
                ismissing(string(item)) || ...
                strlength(string(item)) == 0

            v(i) = ...
                nan;


        else

            v(i) = ...
                str2double( ...
                string(item));

        end

    end

end


function M = cellBlockToDouble(C)

    M = ...
        nan(size(C));


    for i = 1:size(C,1)

        for j = 1:size(C,2)

            item = ...
                C{i,j};


            if isnumeric(item)

                M(i,j) = ...
                    item;


            elseif ...
                    ismissing(string(item)) || ...
                    strlength(string(item)) == 0

                M(i,j) = ...
                    nan;


            else

                M(i,j) = ...
                    str2double( ...
                    string(item));

            end

        end

    end

end